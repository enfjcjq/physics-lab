// ==================== downloadReport ====================

describe("downloadReport", () => {
  let mockCreateObjectURL: ReturnType<typeof vi.fn>;
  let mockRevokeObjectURL: ReturnType<typeof vi.fn>;

  beforeEach(() => {
    mockCreateObjectURL = vi.fn(() => "blob:http://fake-url");
    mockRevokeObjectURL = vi.fn();
    (global as any).URL.createObjectURL = mockCreateObjectURL;
    (global as any).URL.revokeObjectURL = mockRevokeObjectURL;
  });

  it("应创建 Blob 并触发下载", () => {
    downloadReport("test content", "test.md");

    expect(mockCreateObjectURL).toHaveBeenCalledOnce();
    // 验证 a 标签被创建、点击并清理
  });

  it("使用正确的 MIME 类型", () => {
    downloadReport("content", "file.md");
    const callArgs = mockCreateObjectURL.mock.calls[0][0] as Blob;
    expect(callArgs.type).toBe("text/markdown;charset=utf-8");
  });
});

// ==================== captureScreenshot ====================

describe("captureScreenshot", () => {
  beforeEach(() => {
    document.body.innerHTML = "";
    // jsdom 不实现 toDataURL，需要 mock
    HTMLCanvasElement.prototype.toDataURL = vi.fn(() => "data:image/png;base64,fakedata");
  });

  it("默认选择器 #physics-canvas 找不到时应返回 null", () => {
    const result = captureScreenshot();
    expect(result).toBeNull();
  });

  it("自定义选择器找不到时应返回 null", () => {
    const result = captureScreenshot("#nonexistent-canvas");
    expect(result).toBeNull();
  });

  it("找到 canvas 时应返回 PNG data URL", () => {
    // 注入一个测试 canvas
    const canvas = document.createElement("canvas");
    canvas.id = "physics-canvas";
    document.body.appendChild(canvas);

    const result = captureScreenshot();
    expect(result).not.toBeNull();
    expect(result?.startsWith("data:image/png")).toBe(true);
  });

  it("自定义选择器应正确匹配", () => {
    const canvas = document.createElement("canvas");
    canvas.id = "custom-canvas";
    document.body.appendChild(canvas);

    const result = captureScreenshot("#custom-canvas");
    expect(result).not.toBeNull();
  });
});

// ==================== S82: export quality ====================

describe("S82 export quality", () => {
  it("HTML 正文不含原始 Markdown 符号（# ** |）", () => {
    const data = createMockReportData();
    const html = generateHTMLReport(data, "zh-CN");
    const body = html.slice(html.indexOf("<body>"), html.indexOf("</body>"));
    expect(body).not.toMatch(/#{1,3}\s/);
    expect(body).not.toContain("**");
    expect(body).not.toContain("|---");
  });

  it("HTML 表格已转换为 <table> 元素", () => {
    const data = createMockReportData();
    const html = generateHTMLReport(data, "zh-CN");
    expect(html).toContain("<table>");
    expect(html).toContain("<th>");
  });

  it("i18n 键名解析为文案，不泄漏原始键名", () => {
    const data = createMockReportData();
    data.scene.teacher_steps.push({ titleKey: "menu.file", descKey: "menu.file.new", order: 2, timeStart: 0 } as never);
    const result = generateMarkdownReport(data, "zh-CN");
    expect(result).toContain("文件");
    expect(result).toContain("新建实验");
    expect(result).not.toContain("menu.file.new");
  });

  it("无内容的知识点不渲染（不留空壳）", () => {
    const data = createMockReportData();
    data.scene.knowledge_tags.push({ id: "kpEmpty", name: "空知识点", category: "力学", level: 1 } as never);
    const result = generateMarkdownReport(data, "zh-CN");
    expect(result).not.toContain("空知识点");
  });

});
