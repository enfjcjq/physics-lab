// ==================== generateMarkdownReport ====================

describe("generateMarkdownReport", () => {
  it("应生成中文报告（zh-CN）", () => {
    const data = createMockReportData();
    const result = generateMarkdownReport(data, "zh-CN");
    expect(result).toContain("# Physics Lab 实验报告");
    expect(result).toContain("自由落体实验");
    expect(result).toContain("实验概述");
    expect(result).toContain("实验参数");
    expect(result).toContain("当前状态");
    expect(result).toContain("公式");
    expect(result).toContain("知识点");
    expect(result).toContain("教学步骤");
    expect(result).toContain("由 Physics Lab 自动生成");
  });

  it("应生成英文报告（en）", () => {
    const data = createMockReportData();
    const result = generateMarkdownReport(data, "en");
    expect(result).toContain("# Physics Lab Experiment Report");
    expect(result).toContain("Overview");
    expect(result).toContain("Parameters");
    expect(result).toContain("Current State");
    expect(result).toContain("Formulas");
    expect(result).toContain("Knowledge Points");
    expect(result).toContain("Teaching Steps");
    expect(result).toContain("Generated by Physics Lab");
  });

  it("应包含正确的参数表格", () => {
    const data = createMockReportData();
    const result = generateMarkdownReport(data, "zh-CN");
    expect(result).toContain("| 初始高度 h₀ | 10 | m |");
    expect(result).toContain("| 重力加速度 g | 9.8 | m/s² |");
    expect(result).not.toContain("| mass |");
  });

  it("应包含当前状态数值", () => {
    const data = createMockReportData();
    const result = generateMarkdownReport(data, "zh-CN");
    expect(result).toContain("(t = 1.50 s)");
    expect(result).toContain("位置 y");
    expect(result).toContain("8.90 m");
    expect(result).toContain("速度 v");
    expect(result).toContain("-14.70 m/s");
  });

  it("应包含公式和知识点详情", () => {
    const data = createMockReportData();
    const result = generateMarkdownReport(data, "zh-CN");
    expect(result).toContain("位移公式");
    expect(result).toContain("y = h − 0.5·g·t²");
    expect(result).toContain("重力加速度");
    expect(data.scene.knowledge_tags[0].learning_tips && result.includes(data.scene.knowledge_tags[0].learning_tips)).toBe(true);
  });

  it("教学步骤应根据 currentTime 显示完成状态", () => {
    const data = createMockReportData();
    // timeStart=0, currentTime=1.5 >= 0 → 应显示 ✓
    const result = generateMarkdownReport(data, "zh-CN");
    expect(result).toContain("✓");
  });
});

